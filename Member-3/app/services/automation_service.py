from typing import List

from app.schemas.automation import AutomationJob


class AutomationService:
    """
    Creates and tracks automation jobs generated by
    the decision engine.

    Actual automation execution, such as Ansible playbook
    execution, will be integrated separately.
    """

    def __init__(self):
        self._jobs: List[AutomationJob] = []
        self._job_counter = 0

    def create_job(
        self,
        node_id: str,
        action: str,
        rule_id: str,
        reason: str | None = None,
    ) -> AutomationJob:
        """
        Create a new pending automation job.
        """

        self._job_counter += 1

        job = AutomationJob(
            job_id=f"job-{self._job_counter:03d}",
            node_id=node_id,
            action=action,
            rule_id=rule_id,
            status="PENDING",
            reason=reason,
        )

        self._jobs.append(job)

        return job

    def get_all_jobs(self) -> List[AutomationJob]:
        """
        Return all automation jobs.
        """

        return self._jobs

    def get_job(self, job_id: str) -> AutomationJob | None:
        """
        Return a specific automation job by ID.
        """

        for job in self._jobs:
            if job.job_id == job_id:
                return job

        return None


automation_service = AutomationService()